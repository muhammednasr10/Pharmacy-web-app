import type { SuperAdminPageProps } from "./types";
import { useSuperAdminSharedContext } from "./state/shared";
import { useSuperAdminOverviewState } from "./state/useSuperAdminOverviewState";
import { useSuperAdminPricingCalculatorState } from "./state/useSuperAdminPricingCalculatorState";
import { useSuperAdminTenantLimitsState } from "./state/useSuperAdminTenantLimitsState";
import { useSuperAdminRequestsState } from "./state/useSuperAdminRequestsState";
import { useSuperAdminManageTenantState } from "./state/useSuperAdminManageTenantState";
import { useSuperAdminRolesState } from "./state/useSuperAdminRolesState";
import { useSuperAdminSystemUsersState } from "./state/useSuperAdminSystemUsersState";

export function useSuperAdminPageState(props: SuperAdminPageProps) {
  const {
    tenantForm,
    onTenantFormChange,
    creatingTenant,
    onRefreshAdminRequests,
    onRefreshSystemUsers,
    subscriptionRequests,
    pendingPharmacyLoginAccounts,
    pendingPharmacySignupRequests,
    pendingCustomRoles,
    selectedPharmacyId,
    onSelectPharmacy,
    onSwitchTenant,
    onOpenTenantUsers,
    onResetTenantForm,
    onCreateTenant,
    onCreateOrganizationBranch,
    onUpdateOrganizationBranch,
    onDeleteOrganization,
    onDeleteOrganizationBranch,
    onUpdateTenantStatus,
    onUpdateMaxBranches,
    onUpdateMaxUsers,
    onUpdateOrganizationFreeTrial,
    onRefreshPharmacies,
  } = props;

  const shared = useSuperAdminSharedContext(props);

  const overview = useSuperAdminOverviewState({
    isArabic: shared.isArabic,
    pharmacies: shared.pharmacies,
    subscriptionRequests,
    pendingPharmacyLoginAccounts,
    pendingPharmacySignupRequests,
    pendingCustomRoles,
  });

  const manage = useSuperAdminManageTenantState({
    isArabic: shared.isArabic,
    pharmacies: shared.pharmacies,
    selected: shared.selected,
    selectedBranchUsage: shared.selectedBranchUsage,
    selectedOrgBranches: shared.selectedOrgBranches,
    selectedOrgBranchIds: shared.selectedOrgBranchIds,
    expandedOrgIds: overview.expandedOrgIds,
    setExpandedOrgIds: overview.setExpandedOrgIds,
    selectedPharmacyId,
    onSelectPharmacy,
    onSwitchTenant,
    onOpenTenantUsers,
    onResetTenantForm,
    onCreateTenant,
    onCreateOrganizationBranch,
    onUpdateOrganizationBranch,
    onDeleteOrganization,
    onDeleteOrganizationBranch,
    onUpdateTenantStatus,
  });

  const pricing = useSuperAdminPricingCalculatorState({
    isArabic: shared.isArabic,
    operatorUid: shared.operatorUid,
    activeTab: overview.activeTab,
  });

  const limits = useSuperAdminTenantLimitsState({
    isArabic: shared.isArabic,
    selected: shared.selected ?? null,
    manageModalOpen: manage.manageModalOpen,
    setActiveTab: overview.setActiveTab,
    setManageModalOpen: manage.setManageModalOpen,
    onUpdateMaxBranches,
    onUpdateMaxUsers,
    onUpdateOrganizationFreeTrial,
  });

  const requests = useSuperAdminRequestsState({
    isArabic: shared.isArabic,
    pharmacies: shared.pharmacies,
    onApproveSubscriptionRequest: props.onApproveSubscriptionRequest,
    onRejectSubscriptionRequest: props.onRejectSubscriptionRequest,
    onApprovePharmacyLoginAccount: props.onApprovePharmacyLoginAccount,
    onRejectPharmacyLoginAccount: props.onRejectPharmacyLoginAccount,
    onApprovePharmacySignupRequest: props.onApprovePharmacySignupRequest,
    onRejectPharmacySignupRequest: props.onRejectPharmacySignupRequest,
    onRefreshAdminRequests,
  });

  const roles = useSuperAdminRolesState({
    isArabic: shared.isArabic,
    pharmacies: shared.pharmacies,
    selected: shared.selected,
    activeTab: overview.activeTab,
    manageModalOpen: manage.manageModalOpen,
    reloadManageRoles: manage.reloadManageRoles,
    onRefreshSystemUsers,
  });

  const systemUsersState = useSuperAdminSystemUsersState({
    isArabic: shared.isArabic,
    operatorUid: shared.operatorUid,
    selected: shared.selected,
    selectedOrgBranches: shared.selectedOrgBranches,
    manageCustomRoles: manage.manageCustomRoles,
    manageRoleConfigs: manage.manageRoleConfigs,
    manageEmployees: manage.manageEmployees,
    manageLoginAccounts: manage.manageLoginAccounts,
    manageOrgSystemUsers: manage.manageOrgSystemUsers,
    manageRoleAccountDisplayRows: manage.manageRoleAccountDisplayRows,
    canPickSystemUserBranch: manage.canPickSystemUserBranch,
    reloadManageRoles: manage.reloadManageRoles,
    resolveBuiltinRoleLabels: manage.resolveBuiltinRoleLabels,
    onRefreshSystemUsers,
  });

  return {
    isArabic: shared.isArabic,
    operatorUid: shared.operatorUid,
    pharmacies: shared.pharmacies,
    systemUsers: shared.systemUsers,
    selectedPharmacyId,
    tenantForm,
    onTenantFormChange,
    creatingTenant,
    onRefreshAdminRequests,
    onRefreshSystemUsers,
    subscriptionRequests,
    pendingPharmacyLoginAccounts,
    pendingCustomRoles,
    pendingPharmacySignupRequests,
    addModalOpen: manage.addModalOpen,
    setAddModalOpen: manage.setAddModalOpen,
    manageModalOpen: manage.manageModalOpen,
    setManageModalOpen: manage.setManageModalOpen,
    branchModalMode: manage.branchModalMode,
    branchForm: manage.branchForm,
    setBranchForm: manage.setBranchForm,
    creatingBranch: manage.creatingBranch,
    deletingBranchId: manage.deletingBranchId,
    manageRolesLoading: manage.manageRolesLoading,
    manageCustomRoles: manage.manageCustomRoles,
    manageRoleConfigs: manage.manageRoleConfigs,
    manageEmployees: manage.manageEmployees,
    manageLoginAccounts: manage.manageLoginAccounts,
    manageOrgSystemUsers: manage.manageOrgSystemUsers,
    roleModalOpen: roles.roleModalOpen,
    roleForm: roles.roleForm,
    setRoleForm: roles.setRoleForm,
    savingRole: roles.savingRole,
    deletingRoleId: roles.deletingRoleId,
    systemUserModalOpen: systemUsersState.systemUserModalOpen,
    systemUserModalMode: systemUsersState.systemUserModalMode,
    editingSystemUserUid: systemUsersState.editingSystemUserUid,
    systemUserForm: systemUsersState.systemUserForm,
    setSystemUserForm: systemUsersState.setSystemUserForm,
    savingSystemUser: systemUsersState.savingSystemUser,
    systemUserBusyUid: systemUsersState.systemUserBusyUid,
    showSystemUserPassword: systemUsersState.showSystemUserPassword,
    setShowSystemUserPassword: systemUsersState.setShowSystemUserPassword,
    statusTarget: manage.statusTarget,
    setStatusTarget: manage.setStatusTarget,
    statusUpdating: manage.statusUpdating,
    deleteTarget: manage.deleteTarget,
    setDeleteTarget: manage.setDeleteTarget,
    deleteUpdating: manage.deleteUpdating,
    pricingCalculatorForm: pricing.pricingCalculatorForm,
    setPricingCalculatorForm: pricing.setPricingCalculatorForm,
    savingPricingCalculator: pricing.savingPricingCalculator,
    savePricingCalculatorConfig: pricing.savePricingCalculatorConfig,
    selected: shared.selected,
    selectedBranchUsage: shared.selectedBranchUsage,
    selectedUserUsage: shared.selectedUserUsage,
    selectedOrgBranches: shared.selectedOrgBranches,
    selectedTier: shared.selectedTier,
    selectedTierCap: shared.selectedTierCap,
    selectedTrialStatus: shared.selectedTrialStatus,
    freeTrialDraft: limits.freeTrialDraft,
    setFreeTrialDraft: limits.setFreeTrialDraft,
    freeTrialSavingId: limits.freeTrialSavingId,
    activeTab: overview.activeTab,
    setActiveTab: overview.setActiveTab,
    customerRequestFilter: overview.customerRequestFilter,
    setCustomerRequestFilter: overview.setCustomerRequestFilter,
    expandedOrgIds: overview.expandedOrgIds,
    rolesReferenceLoading: roles.rolesReferenceLoading,
    rolesReferenceQuery: roles.rolesReferenceQuery,
    setRolesReferenceQuery: roles.setRolesReferenceQuery,
    pendingCustomerRequestsCount: overview.pendingCustomerRequestsCount,
    pharmacyNameById: overview.pharmacyNameById,
    requestUpdating: requests.requestUpdating,
    signupApproveTarget: requests.signupApproveTarget,
    signupApproveTier: requests.signupApproveTier,
    setSignupApproveTier: requests.setSignupApproveTier,
    closeSignupApproveModal: requests.closeSignupApproveModal,
    confirmSignupApprove: requests.confirmSignupApprove,
    maxBranchSavingId: limits.maxBranchSavingId,
    maxUserSavingId: limits.maxUserSavingId,
    maxBranchDrafts: limits.maxBranchDrafts,
    setMaxBranchDrafts: limits.setMaxBranchDrafts,
    maxUserDrafts: limits.maxUserDrafts,
    setMaxUserDrafts: limits.setMaxUserDrafts,
    saasTabs: overview.saasTabs,
    customerRequestRows: overview.customerRequestRows,
    pharmacyOrgGroups: overview.pharmacyOrgGroups,
    filteredProgramRoleListRows: roles.filteredProgramRoleListRows,
    manageUnifiedRoleRows: manage.manageUnifiedRoleRows,
    manageRoleAccountDisplayRows: manage.manageRoleAccountDisplayRows,
    manageUnifiedRolesTableColSpan: manage.manageUnifiedRolesTableColSpan,
    manageOrphanSystemUsers: systemUsersState.manageOrphanSystemUsers,
    manageEmployeeById: manage.manageEmployeeById,
    manageRoleSelectEntries: systemUsersState.manageRoleSelectEntries,
    canPickSystemUserBranch: manage.canPickSystemUserBranch,
    operatorAppUser: systemUsersState.operatorAppUser,
    reloadRolesReference: roles.reloadRolesReference,
    reloadManageRoles: manage.reloadManageRoles,
    getMaxBranchDraft: limits.getMaxBranchDraft,
    getMaxUserDraft: limits.getMaxUserDraft,
    saveFreeTrial: limits.saveFreeTrial,
    saveMaxUsers: limits.saveMaxUsers,
    saveMaxBranches: limits.saveMaxBranches,
    handleApproveRequest: requests.handleApproveRequest,
    handleRejectRequest: requests.handleRejectRequest,
    handleApproveLoginRequest: requests.handleApproveLoginRequest,
    handleRejectLoginRequest: requests.handleRejectLoginRequest,
    handleApproveSignupRequest: requests.handleApproveSignupRequest,
    handleRejectSignupRequest: requests.handleRejectSignupRequest,
    handleApproveRoleRequest: requests.handleApproveRoleRequest,
    handleRejectRoleRequest: requests.handleRejectRoleRequest,
    openManage: manage.openManage,
    closeAddModal: manage.closeAddModal,
    submitCreateTenant: manage.submitCreateTenant,
    openAddBranchModal: manage.openAddBranchModal,
    openEditBranchModal: manage.openEditBranchModal,
    closeBranchModal: manage.closeBranchModal,
    submitBranchForm: manage.submitBranchForm,
    deleteBranch: manage.deleteBranch,
    openAddRoleModal: roles.openAddRoleModal,
    openEditBuiltinRole: roles.openEditBuiltinRole,
    tryDeleteBuiltinRole: roles.tryDeleteBuiltinRole,
    openEditRoleModal: roles.openEditRoleModal,
    closeRoleModal: roles.closeRoleModal,
    handleOpenEmployeesPage: manage.handleOpenEmployeesPage,
    saveRoleForm: roles.saveRoleForm,
    activateCustomRole: roles.activateCustomRole,
    deleteCustomRole: roles.deleteCustomRole,
    openAddSystemUserModal: systemUsersState.openAddSystemUserModal,
    openEditSystemUserModal: systemUsersState.openEditSystemUserModal,
    closeSystemUserModal: systemUsersState.closeSystemUserModal,
    saveSystemUserForm: systemUsersState.saveSystemUserForm,
    deleteSystemUserRow: systemUsersState.deleteSystemUserRow,
    confirmStatusChange: manage.confirmStatusChange,
    confirmDelete: manage.confirmDelete,
    handleViewAsTenant: manage.handleViewAsTenant,
    formatEndDateAfterApproval: requests.formatEndDateAfterApproval,
    getCustomerRequestResult: requests.getCustomerRequestResult,
    isCustomerRequestBusy: requests.isCustomerRequestBusy,
    toggleOrgExpanded: overview.toggleOrgExpanded,
    openPricingTabFromManage: limits.openPricingTabFromManage,
  };
}

export type SuperAdminPageState = ReturnType<typeof useSuperAdminPageState>;
