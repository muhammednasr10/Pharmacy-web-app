import { useMemo } from "react";
import type { EmployeesUsersPageProps } from "./types";
import { staffActionErrorMessage } from "./helpers";
import { buildPharmacyRoleSelectOptions } from "../../utils/pharmacyGeneralManager";
import { useStaffSharedContext, useStaffSharedDerived } from "./state/shared";
import { useStaffDataState } from "./state/useStaffDataState";
import { useStaffLoginCatalogState } from "./state/useStaffLoginCatalogState";
import { useStaffPermissionsState } from "./state/useStaffPermissionsState";
import { useStaffEmployeesState } from "./state/useStaffEmployeesState";

export function useEmployeesUsersPageState(props: EmployeesUsersPageProps) {
  const shared = useStaffSharedContext(props);

  const data = useStaffDataState({
    appUser: shared.appUser,
    pharmacyId: shared.pharmacyId,
    loadOrgEmployeeScope: shared.loadOrgEmployeeScope,
    shouldLoadLoginCatalog: shared.shouldLoadLoginCatalog,
    orgBranchIds: shared.orgBranchIds,
    canViewLoginAccountsTab: shared.canViewLoginAccountsTab,
    setLoading: shared.setLoading,
    setLoadError: shared.setLoadError,
  });

  const derived = useStaffSharedDerived({
    isArabic: shared.isArabic,
    appUser: shared.appUser,
    pharmacyId: shared.pharmacyId,
    tenantScopePharmacyId: shared.tenantScopePharmacyId,
    showOrgHr: shared.showOrgHr,
    canFilterEmployeesByBranch: shared.canFilterEmployeesByBranch,
    isTenantScopedView: shared.isTenantScopedView,
    orgBranchIds: shared.orgBranchIds,
    employeeBranchFilter: shared.employeeBranchFilter,
    loginAccountsPanelBranchFilter: shared.loginAccountsPanelBranchFilter,
    branchDirectory: shared.branchDirectory,
    pharmacies: shared.pharmacies,
    employees: data.employees,
    loginCatalog: data.loginCatalog,
    systemUsers: data.systemUsers,
  });

  const loginCatalog = useStaffLoginCatalogState({
    isArabic: shared.isArabic,
    appUser: shared.appUser,
    pharmacyId: shared.pharmacyId,
    tenantScopePharmacyId: shared.tenantScopePharmacyId,
    currentUid: shared.currentUid,
    onActivityLog: shared.onActivityLog,
    canViewLoginAccountsTab: shared.canViewLoginAccountsTab,
    canManageLoginAccountsCatalog: shared.canManageLoginAccountsCatalog,
    branchDirectory: shared.branchDirectory,
    orgBranchIds: shared.orgBranchIds,
    catalogBranchFilter: shared.catalogBranchFilter,
    setCatalogBranchFilter: shared.setCatalogBranchFilter,
    employeeBranchFilter: shared.employeeBranchFilter,
    loginAccountsPanelBranchFilter: shared.loginAccountsPanelBranchFilter,
    setLoginAccountsPanelBranchFilter: shared.setLoginAccountsPanelBranchFilter,
    setEmployeesAccessPanel: shared.setEmployeesAccessPanel,
    busy: shared.busy,
    setBusy: shared.setBusy,
    employeeById: derived.employeeById,
    generalManagerScope: derived.generalManagerScope,
    employeesPanelPharmacyId: derived.employeesPanelPharmacyId,
    loginCatalog: data.loginCatalog,
    customRoles: data.customRoles,
    systemUsers: data.systemUsers,
    orgUserUsage: derived.orgUserUsage,
    loadAll: data.loadAll,
    refreshLoginCatalog: data.refreshLoginCatalog,
  });

  const permissions = useStaffPermissionsState({
    isArabic: shared.isArabic,
    appUser: shared.appUser,
    currentUid: shared.currentUid,
    setBusy: shared.setBusy,
    catalogByEmployeeId: derived.catalogByEmployeeId,
    customRoles: data.customRoles,
    systemUsers: data.systemUsers,
    catalogTargetPharmacyId: loginCatalog.catalogTargetPharmacyId,
    loadAll: data.loadAll,
  });

  const employees = useStaffEmployeesState({
    isArabic: shared.isArabic,
    appUser: shared.appUser,
    pharmacyId: shared.pharmacyId,
    pharmacies: shared.pharmacies,
    currency: shared.currency,
    onActivityLog: shared.onActivityLog,
    showOrgHrManage: shared.showOrgHrManage,
    canManage: shared.canManage,
    canViewLoginAccountsTab: shared.canViewLoginAccountsTab,
    busy: shared.busy,
    setBusy: shared.setBusy,
    branchLabel: shared.branchLabel,
    employeeById: derived.employeeById,
    catalogByEmployeeId: derived.catalogByEmployeeId,
    generalManagerScope: derived.generalManagerScope,
    loginCatalogByPharmacy: derived.loginCatalogByPharmacy,
    loginCatalog: data.loginCatalog,
    customRoles: data.customRoles,
    systemUsers: data.systemUsers,
    loadAll: data.loadAll,
    syncSavedCatalogAccount: loginCatalog.syncSavedCatalogAccount,
    branchCustomRoles: loginCatalog.branchCustomRoles,
    enabledRoleKeys: permissions.resolvedEnabledRoleKeys,
  });

  const loginAccountRoleSelectOptions = useMemo(() => {
    const editingAccount = loginCatalog.editCatalogId
      ? loginCatalog.branchLoginCatalog.find((item) => item.id === loginCatalog.editCatalogId)
      : undefined;
    const options = buildPharmacyRoleSelectOptions({
      pharmacyId: loginCatalog.catalogTargetPharmacyId,
      customRoles: data.customRoles,
      appUser: shared.appUser,
      enabledRoleKeys: permissions.resolvedEnabledRoleKeys,
      generalManagerScope: derived.generalManagerScope,
      accountId: loginCatalog.editCatalogId || undefined,
      currentRole: editingAccount?.role,
    });
    if (editingAccount?.role && !options.includes(editingAccount.role)) {
      return [...options, editingAccount.role];
    }
    return options;
  }, [
    loginCatalog.editCatalogId,
    loginCatalog.branchLoginCatalog,
    loginCatalog.catalogTargetPharmacyId,
    data.customRoles,
    shared.appUser,
    permissions.resolvedEnabledRoleKeys,
    derived.generalManagerScope,
  ]);

  return {
    // Shared page context
    isArabic: shared.isArabic,
    appUser: shared.appUser,
    pharmacyId: shared.pharmacyId,
    pharmacies: shared.pharmacies,
    tenantScopePharmacyId: shared.tenantScopePharmacyId,
    currency: shared.currency,
    currentUid: shared.currentUid,
    onActivityLog: shared.onActivityLog,
    onOpenSubscriptionSettings: shared.onOpenSubscriptionSettings,
    isAccountantOnly: shared.isAccountantOnly,
    activeTab: shared.activeTab,
    setActiveTab: shared.setActiveTab,
    loading: shared.loading,
    busy: shared.busy,
    setBusy: shared.setBusy,
    loadError: shared.loadError,
    canManage: shared.canManage,
    canManageRolePermissions: shared.canManageRolePermissions,
    isOrgManager: shared.isOrgManager,
    isTenantScopedView: shared.isTenantScopedView,
    branchDirectory: shared.branchDirectory,
    orgTier: shared.orgTier,
    showOrgHrManage: shared.showOrgHrManage,
    showOrgHr: shared.showOrgHr,
    showEmployeesBranchColumn: shared.showEmployeesBranchColumn,
    canFilterEmployeesByBranch: shared.canFilterEmployeesByBranch,
    orgHrReadOnly: shared.orgHrReadOnly,
    hrManagePharmacyId: shared.hrManagePharmacyId,
    canViewLoginAccountsTab: shared.canViewLoginAccountsTab,
    canManageLoginAccountsCatalog: shared.canManageLoginAccountsCatalog,
    canRequestLoginAccounts: shared.canRequestLoginAccounts,
    canShowEmployeesAccessPanels: shared.canShowEmployeesAccessPanels,
    shouldLoadLoginCatalog: shared.shouldLoadLoginCatalog,
    loadOrgEmployeeScope: shared.loadOrgEmployeeScope,
    centralHrUpgradeNotice: shared.centralHrUpgradeNotice,
    orgBranchIds: shared.orgBranchIds,
    employeeBranchFilter: shared.employeeBranchFilter,
    setEmployeeBranchFilter: shared.setEmployeeBranchFilter,
    catalogBranchFilter: shared.catalogBranchFilter,
    setCatalogBranchFilter: shared.setCatalogBranchFilter,
    employeesAccessPanel: shared.employeesAccessPanel,
    setEmployeesAccessPanel: shared.setEmployeesAccessPanel,
    loginAccountsPanelBranchFilter: shared.loginAccountsPanelBranchFilter,
    setLoginAccountsPanelBranchFilter: shared.setLoginAccountsPanelBranchFilter,
    isCatalogOwner: shared.isCatalogOwner,
    pharmacyName: shared.pharmacyName,
    branchLabel: shared.branchLabel,
    tabs: shared.tabs,
    isHrTab: shared.isHrTab,
    hasRole: shared.hasRole,

    // Loaded data
    employees: data.employees,
    loginCatalog: data.loginCatalog,
    customRoles: data.customRoles,
    roleConfigs: data.roleConfigs,
    systemUsers: data.systemUsers,
    activityLogs: data.activityLogs,
    loadAll: data.loadAll,
    refreshLoginCatalog: data.refreshLoginCatalog,
    staffActivity: data.staffActivity,

    // Derived maps / filters
    employeeById: derived.employeeById,
    pendingCatalogAccounts: derived.pendingCatalogAccounts,
    orgUserUsage: derived.orgUserUsage,
    catalogByEmployeeId: derived.catalogByEmployeeId,
    employeesPanelPharmacyId: derived.employeesPanelPharmacyId,
    loginCatalogByEmail: derived.loginCatalogByEmail,
    generalManagerScope: derived.generalManagerScope,
    systemUserByEmail: derived.systemUserByEmail,
    loginCatalogByPharmacy: derived.loginCatalogByPharmacy,
    filteredEmployees: derived.filteredEmployees,

    // Login catalog
    catalogTargetPharmacyId: loginCatalog.catalogTargetPharmacyId,
    branchLoginCatalog: loginCatalog.branchLoginCatalog,
    branchCustomRoles: loginCatalog.branchCustomRoles,
    employeesPanelLoginAccounts: loginCatalog.employeesPanelLoginAccounts,
    employeesPanelAccessUsers: loginCatalog.employeesPanelAccessUsers,
    accountModal: loginCatalog.accountModal,
    setAccountModal: loginCatalog.setAccountModal,
    editCatalogId: loginCatalog.editCatalogId,
    setEditCatalogId: loginCatalog.setEditCatalogId,
    catalogForm: loginCatalog.catalogForm,
    setCatalogForm: loginCatalog.setCatalogForm,
    loginAccountRoleSelectOptions,
    approveCatalogAccount: loginCatalog.approveCatalogAccount,
    approveCatalogEdit: loginCatalog.approveCatalogEdit,
    approveCatalogLink: loginCatalog.approveCatalogLink,
    unlinkCatalogAccount: loginCatalog.unlinkCatalogAccount,
    openLoginAccountsPanel: loginCatalog.openLoginAccountsPanel,
    openLoginAccountRequestFromEmployeesPanel: loginCatalog.openLoginAccountRequestFromEmployeesPanel,
    openCatalogAccountAdd: loginCatalog.openCatalogAccountAdd,
    openCatalogAccountEdit: loginCatalog.openCatalogAccountEdit,
    openCatalogAccountDuplicate: loginCatalog.openCatalogAccountDuplicate,
    onCatalogFormRoleChange: loginCatalog.onCatalogFormRoleChange,
    openPasswordChangeRequest: loginCatalog.openPasswordChangeRequest,
    savePasswordChangeRequest: loginCatalog.savePasswordChangeRequest,
    saveCatalogAccount: loginCatalog.saveCatalogAccount,
    deleteCatalogAccount: loginCatalog.deleteCatalogAccount,
    renderLoginAccountLinkStatus: loginCatalog.renderLoginAccountLinkStatus,
    renderSystemUserStatus: loginCatalog.renderSystemUserStatus,
    formatLoginAccountOptionLabel: loginCatalog.formatLoginAccountOptionLabel,

    // Per-employee permission editor (role toggles live in Settings)
    permissionEditorTarget: permissions.permissionEditorTarget,
    setPermissionEditorTarget: permissions.setPermissionEditorTarget,
    permissionEditorPages: permissions.permissionEditorPages,
    setPermissionEditorPages: permissions.setPermissionEditorPages,
    permissionEditorPermissions: permissions.permissionEditorPermissions,
    setPermissionEditorPermissions: permissions.setPermissionEditorPermissions,
    resolvedEnabledRoleKeys: permissions.resolvedEnabledRoleKeys,
    isCurrentAppEmployee: permissions.isCurrentAppEmployee,
    openPermissionEditorForEmployee: permissions.openPermissionEditorForEmployee,
    savePermissionEditor: permissions.savePermissionEditor,
    resetPermissionEditorDefaults: permissions.resetPermissionEditorDefaults,

    // Employees CRUD / assignment / salary card
    employeeModal: employees.employeeModal,
    setEmployeeModal: employees.setEmployeeModal,
    attendanceBadgeEmployee: employees.attendanceBadgeEmployee,
    setAttendanceBadgeEmployee: employees.setAttendanceBadgeEmployee,
    profileModalEmployee: employees.profileModalEmployee,
    setProfileModalEmployee: employees.setProfileModalEmployee,
    openEmployeeProfileModal: employees.openEmployeeProfileModal,
    closeEmployeeProfileModal: employees.closeEmployeeProfileModal,
    salaryModalEmployee: employees.salaryModalEmployee,
    salaryModalRecord: employees.salaryModalRecord,
    salaryModalLoading: employees.salaryModalLoading,
    salaryModalError: employees.salaryModalError,
    salaryPeriodStart: employees.salaryPeriodStart,
    setSalaryPeriodStart: employees.setSalaryPeriodStart,
    salaryPeriodEnd: employees.salaryPeriodEnd,
    setSalaryPeriodEnd: employees.setSalaryPeriodEnd,
    salaryBusyAction: employees.salaryBusyAction,
    salaryAdditionsModal: employees.salaryAdditionsModal,
    setSalaryAdditionsModal: employees.setSalaryAdditionsModal,
    salaryDeductionsModal: employees.salaryDeductionsModal,
    setSalaryDeductionsModal: employees.setSalaryDeductionsModal,
    payrollConfig: employees.payrollConfig,
    canEditSalaryRecord: employees.canEditSalaryRecord,
    openEmployeeSalaryModal: employees.openEmployeeSalaryModal,
    closeEmployeeSalaryModal: employees.closeEmployeeSalaryModal,
    refreshEmployeeSalaryModal: employees.refreshEmployeeSalaryModal,
    editSalaryBaseSalary: employees.editSalaryBaseSalary,
    openSalaryAdditionsModal: employees.openSalaryAdditionsModal,
    saveSalaryAdditions: employees.saveSalaryAdditions,
    openSalaryDeductionsModal: employees.openSalaryDeductionsModal,
    editEmployeeId: employees.editEmployeeId,
    setEditEmployeeId: employees.setEditEmployeeId,
    employeeForm: employees.employeeForm,
    setEmployeeForm: employees.setEmployeeForm,
    pharmacyShifts: employees.pharmacyShifts,
    pharmacyDefaultShiftId: employees.pharmacyDefaultShiftId,
    transferEmployee: employees.transferEmployee,
    setTransferEmployee: employees.setTransferEmployee,
    transferTargetBranchId: employees.transferTargetBranchId,
    setTransferTargetBranchId: employees.setTransferTargetBranchId,
    openAddEmployee: employees.openAddEmployee,
    openEditEmployee: employees.openEditEmployee,
    updateEmployeeWorkSchedule: employees.updateEmployeeWorkSchedule,
    saveEmployee: employees.saveEmployee,
    openTransferEmployeeModal: employees.openTransferEmployeeModal,
    confirmTransferEmployee: employees.confirmTransferEmployee,
    deleteEmployeeRecord: employees.deleteEmployeeRecord,
    toggleEmployeeActive: employees.toggleEmployeeActive,
    assignEmployeeLoginAccount: employees.assignEmployeeLoginAccount,
    assignEmployeeRole: employees.assignEmployeeRole,
    renderEmployeeRoleCell: employees.renderEmployeeRoleCell,
    assignEmployeeSystemUser: employees.assignEmployeeSystemUser,
    renderEmployeeLoginCell: employees.renderEmployeeLoginCell,
    getEmployeeAssignedAccountId: employees.getEmployeeAssignedAccountId,
    getEmployeeLinkedUserUid: employees.getEmployeeLinkedUserUid,
    employeeLoginAccountOptionsFor: employees.employeeLoginAccountOptionsFor,
    employeeRoleOptionsFor: employees.employeeRoleOptionsFor,
    getEmployeeSelectedRole: employees.getEmployeeSelectedRole,

    staffActionErrorMessage: (err: unknown, fallback: string) =>
      staffActionErrorMessage(err, shared.isArabic, fallback),
  };
}

export type EmployeesUsersPageState = ReturnType<typeof useEmployeesUsersPageState>;
